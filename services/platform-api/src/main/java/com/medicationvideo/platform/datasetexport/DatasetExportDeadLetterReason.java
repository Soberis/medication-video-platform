package com.medicationvideo.platform.datasetexport;

enum DatasetExportDeadLetterReason {

	DATASET_EXPORT_JOB_CONTRACT_INVALID, DATASET_EXPORT_JOB_PROFILE_UNSUPPORTED, DATASET_EXPORT_JOB_ACQUIRE_REJECTED,
	DATASET_EXPORT_JOB_LEASE_REJECTED, DATASET_EXPORT_JOB_RESULT_REJECTED;

	boolean replayable() {
		return this != DATASET_EXPORT_JOB_CONTRACT_INVALID;
	}

}
