function freezeDeep(value) {
  if (value && typeof value === 'object' && !Object.isFrozen(value)) {
    Object.values(value).forEach(freezeDeep)
    Object.freeze(value)
  }
  return value
}

export const SCENARIOS = freezeDeep(SCENARIO_DEFINITIONS)
export const SCENARIO_NAMES = Object.freeze(Object.keys(SCENARIOS))

export function getScenario(name) {
  const scenario = SCENARIOS[name]
  if (!scenario) {
    throw new RangeError(`Unknown synthetic CaptureGroup scenario: ${name}`)
  }
  return scenario
}

function validateRunId(runId) {
  if (typeof runId !== 'string' || !/^[A-Za-z0-9._:-]{1,48}$/.test(runId)) {
    throw new TypeError('Synthetic acceptance run id must contain only safe identifier characters')
  }
  return runId
}

export function buildScenarioFixture(name, runId = 'local') {
  const definition = getScenario(name)
  const safeRunId = validateRunId(runId)
  const expectedCameraNumbers = [...definition.expectedCameraNumbers]
  const presentCameraNumbers = [...definition.presentCameraNumbers]
  const missingCameraNumbers = expectedCameraNumbers.filter(
    (cameraNumber) => !presentCameraNumbers.includes(cameraNumber),
  )
  const qualityByCamera = Object.fromEntries(
    presentCameraNumbers.map((cameraNumber) => [cameraNumber, definition.viewQuality?.[cameraNumber] ?? 'QUALIFIED']),
  )

  return {
    name,
    description: definition.description,
    captureGroupKey: `synthetic-acceptance-${name}-${safeRunId}`,
    expectedCameraNumbers,
    presentCameraNumbers,
    missingCameraNumbers,
    receiptAfterFinalize: definition.receiptAfterFinalize,
    finalizeReceipt: definition.finalizeReceipt ?? true,
    mediaMode: definition.mediaMode ?? 'valid',
    mediaProbeExpected: definition.mediaProbeExpected ?? 'SUCCEEDED',
    groupQuality: definition.groupQuality ?? null,
    qualityByCamera,
    candidateExpected: definition.candidateExpected ?? null,
    reviewSequence: [...(definition.reviewSequence ?? [])],
    cleaningOutcome: definition.cleaningOutcome ?? null,
    expectedGroupQualityError: definition.expectedGroupQualityError ?? null,
    expectedFinalRevision: definition.expectedFinalRevision ?? 1,
    inputChangeAfterReview: definition.inputChangeAfterReview
      ? { ...definition.inputChangeAfterReview }
      : null,
    stopAfter: definition.stopAfter ?? null,
    verifyReceivingQualityGate: definition.verifyReceivingQualityGate ?? false,
    primaryCameraNumber: 1,
    actionSegments: DEFAULT_ACTION_SEGMENTS.map((segment) => ({ ...segment })),
    capturedAt: BASE_CAPTURED_AT,
    deviceId: `synthetic-acceptance-${name}-${safeRunId}.device-01`,
    sourceBatchId: `synthetic-acceptance-${name}-${safeRunId}`,
  }
}
